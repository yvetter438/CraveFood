/**
 * Writes public/analytics-config.js from the environment.
 * - Vercel: set CRAVE_POSTHOG_KEY (and optional CRAVE_POSTHOG_API_HOST) in Project → Environment Variables; available at build time.
 * - Local: same vars in .env (only applied when not already in process.env).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outPath = path.join(root, "public", "analytics-config.js");

function loadEnvFile() {
  const p = path.join(root, ".env");
  if (!fs.existsSync(p)) return;
  for (const line of fs.readFileSync(p, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq < 1) continue;
    const k = t.slice(0, eq).trim();
    if (process.env[k] !== undefined) continue;
    let v = t.slice(eq + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'")))
      v = v.slice(1, -1);
    process.env[k] = v;
  }
}
loadEnvFile();

const key = (process.env.CRAVE_POSTHOG_KEY || "").trim();
const host = (process.env.CRAVE_POSTHOG_API_HOST || "https://us.i.posthog.com").replace(/\/$/, "");
const gaId = (process.env.CRAVE_GA_MEASUREMENT_ID || "G-9DY2B1YRPL").trim();

const contents = `/**
 * Generated by scripts/inject-analytics-config.mjs — do not edit.
 * Env: CRAVE_POSTHOG_KEY, CRAVE_POSTHOG_API_HOST, CRAVE_GA_MEASUREMENT_ID
 * See public/analytics-config.example.js
 */
window.CRAVE_POSTHOG_KEY = ${JSON.stringify(key)};
window.CRAVE_POSTHOG_API_HOST = ${JSON.stringify(host)};
window.CRAVE_GA_MEASUREMENT_ID = ${JSON.stringify(gaId)};
`;
fs.writeFileSync(outPath, contents, "utf8");
console.log(
  "inject-analytics-config:",
  outPath,
  key ? "PostHog ok" : "PostHog empty",
  gaId ? `GA ${gaId}` : "GA empty"
);
